#!/usr/bin/env bash
# Keeps po/POTFILES.in in sync with the sources that contain translatable strings.
#
#   build-aux/check-potfiles.sh           fail (and show a diff) if POTFILES.in is stale
#   build-aux/check-potfiles.sh --update  rewrite POTFILES.in
#
# Rust files count when they call gettext/ngettext/pgettext/npgettext; Blueprint files
# when they use _() or C_(). The desktop, metainfo and schema files are always listed.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

generate() {
    echo "# List of source files containing translatable strings."
    echo "# Generated by build-aux/check-potfiles.sh --update; do not edit by hand."
    echo "data/dev.m5ka.Lio.desktop.in"
    echo "data/dev.m5ka.Lio.metainfo.xml.in"
    echo "data/dev.m5ka.Lio.gschema.xml"
    grep -rlE '\bC?_\(' --include='*.blp' data/resources/ui | LC_ALL=C sort
    grep -rlE '\b(n|p|np)?gettext\(' --include='*.rs' src | LC_ALL=C sort
}

if [[ "${1:-}" == "--update" ]]; then
    generate > po/POTFILES.in
    echo "po/POTFILES.in updated"
elif ! diff -u po/POTFILES.in <(generate); then
    echo "po/POTFILES.in is out of date; run build-aux/check-potfiles.sh --update" >&2
    exit 1
fi
